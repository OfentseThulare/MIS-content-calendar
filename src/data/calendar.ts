// Group calendar by week for grid rendering.
export function calendarByWeek(): { weekNumber: number; phase: import('./phases').PhaseKey; posts: CalendarPost[] }[] {
  const map = new Map<number, CalendarPost[]>()
  for (const post of calendar) {
    const list = map.get(post.weekNumber) ?? []
    list.push(post)
    map.set(post.weekNumber, list)
  }
  return Array.from(map.entries())
    .sort(([a], [b]) => a - b)
    .map(([weekNumber, posts]) => ({
      weekNumber,
      phase: posts[0].phase,
      posts: posts.sort((a, b) => dayOrder(a.day) - dayOrder(b.day)),
    }))
}

function dayOrder(d: CalendarDay): number {
  return ({ Mon: 1, Tue: 2, Wed: 3, Thu: 4, Fri: 5 } as const)[d]
}

